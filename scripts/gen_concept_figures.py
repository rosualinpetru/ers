#!/usr/bin/env python3
"""
Generate the conceptual (non-benchmark) figures of the paper as TikZ.

Every figure is *computed* with the library's own structures rather than drawn
by hand, so what the paper shows is what the code does:

* ``fig_domains.tex``      -- one query box on the native grid (product
  range-tree BRC) and on the Hilbert curve (segments and their 1-D BRC).
* ``fig_curve_ranges.tex`` -- the canonical ranges of the curve range tree are
  boxes, and a product range that is not a curve interval.
* ``fig_rtree_packing.tex`` -- leaves of a Hilbert-packed and an STR-packed
  R-tree over the same point set.
* ``fig_divider.tex``      -- uniform and mass-based TDAG cuts over the same
  one-dimensional data.
* ``fig_interactive.tex``  -- the two rounds of the interactive double index.

Usage: ``python3 scripts/gen_concept_figures.py [--out figures/concept]``
"""
from __future__ import annotations

import argparse
import random
from pathlib import Path
from typing import Dict, List, Tuple

from ers.schemes.common.structure_builders import uniform_tree, uniform_tree_product
from ers.structures.hilbert_curve import HilbertCurve
from ers.structures.hilbert_rtree import HilbertRTree
from ers.structures.hyperrange import HyperRange
from ers.structures.point import Point
from ers.structures.str_rtree import STRRTree
from ers.util.hyperrange.data_dependent_split_mid_overlap_divider import DataDependentSplitMidOverlapDivider
from ers.util.hyperrange.uniform_split_mid_overlap_divider import UniformSplitMidOverlapDivider

# Grey-scale friendly fills; the paper is printed in black and white too.
FILL_QUERY = "black!12"
FILL_COVER = ["blue!18", "orange!25", "green!22", "purple!18", "red!15", "cyan!20", "yellow!35", "brown!22"]


def _rect(r: HyperRange, style: str) -> str:
    (x0, y0), (x1, y1) = r.start.coords(), r.end.coords()
    return f"  \\draw[{style}] ({x0},{y0}) rectangle ({x1 + 1},{y1 + 1});\n"


def _cells(cells: List[Point], style: str) -> str:
    return "".join(f"  \\fill[{style}] ({p[0]},{p[1]}) rectangle ({p[0] + 1},{p[1] + 1});\n" for p in cells)


def _curve_path(hc: HilbertCurve, n_cells: int, style: str) -> str:
    pts = [hc.point_from_distance(d) for d in range(n_cells)]
    coords = " -- ".join(f"({p[0] + 0.5},{p[1] + 0.5})" for p in pts)
    return f"  \\draw[{style}] {coords};\n"


def _curve_run(hc: HilbertCurve, lo: int, hi: int, style: str) -> str:
    pts = [hc.point_from_distance(d) for d in range(lo, hi + 1)]
    if len(pts) == 1:
        p = pts[0]
        return f"  \\fill[{style}] ({p[0] + 0.5},{p[1] + 0.5}) circle (0.16);\n"
    coords = " -- ".join(f"({p[0] + 0.5},{p[1] + 0.5})" for p in pts)
    return f"  \\draw[{style}] {coords};\n"


# --------------------------------------------------------------------------- #
# Figure 1: the two domain representations of one query
# --------------------------------------------------------------------------- #
def fig_domains(order: int = 3, query=((2, 1), (5, 4))) -> str:
    side = 2**order
    hc = HilbertCurve(order, 2)
    q = HyperRange.from_coords(list(query[0]), list(query[1]))
    product = uniform_tree_product([order, order])
    native_cover = sorted(product.brc(q), key=lambda r: (r.start[0], r.start[1]))
    segments = hc.brc(q)
    line_tree = uniform_tree([2 * order], 2)
    curve_cover = [r for seg in segments for r in line_tree.brc(HyperRange.from_coords([seg[0]], [seg[1]]))]
    curve_cover.sort(key=lambda r: r.start[0])
    boundary = q.boundary_points()

    s = "% generated by scripts/gen_concept_figures.py -- do not edit\n"
    s += "\\begin{tikzpicture}[x=0.3cm,y=0.3cm,font=\\scriptsize]\n"
    # left panel: native grid with the product BRC
    s += "\\begin{scope}\n"
    s += _cells(q.points(), FILL_QUERY)
    for i, r in enumerate(native_cover):
        s += _rect(r, f"fill={FILL_COVER[i % len(FILL_COVER)]},draw=black,very thick")
    s += f"  \\draw[gray!60,very thin,xstep=1,ystep=1] (0,0) grid ({side},{side});\n"
    s += f"  \\draw[black,thick] ({q.start[0]},{q.start[1]}) rectangle ({q.end[0] + 1},{q.end[1] + 1});\n"
    s += f"  \\node[anchor=north] at ({side / 2},-0.3) {{(a) grid: {len(native_cover)} product-tree ranges}};\n"
    s += "\\end{scope}\n"
    # right panel: the curve, the query, its segments
    dx = side + 2.5
    s += f"\\begin{{scope}}[xshift={dx * 0.3}cm]\n"
    s += _cells(q.points(), FILL_QUERY)
    s += _cells(boundary, "black!28")
    s += f"  \\draw[gray!60,very thin,xstep=1,ystep=1] (0,0) grid ({side},{side});\n"
    s += _curve_path(hc, side * side, "gray!85,thin")
    for i, (lo, hi) in enumerate(segments):
        s += _curve_run(hc, lo, hi, "black,line width=1.6pt")
    s += f"  \\draw[black,thick] ({q.start[0]},{q.start[1]}) rectangle ({q.end[0] + 1},{q.end[1] + 1});\n"
    # label segment endpoints with their distances
    for lo, hi in segments:
        for d in (lo, hi):
            p = hc.point_from_distance(d)
            s += f"  \\node[fill=white,inner sep=0.5pt,font=\\tiny] at ({p[0] + 0.5},{p[1] + 0.5}) {{{d}}};\n"
    s += f"  \\node[anchor=north] at ({side / 2},-0.3) {{(b) curve: {len(segments)} segments}};\n"
    s += "\\end{scope}\n"
    # strip below: the curve domain with the segments and their dyadic cover
    n_cells = side * side
    y0 = -2.6
    sx = (2 * side + 2.5) / n_cells
    s += f"\\begin{{scope}}[yshift={y0 * 0.3}cm,xscale={sx:.5f}]\n"
    s += f"  \\draw[gray!60,thin] (0,0) rectangle ({n_cells},0.8);\n"
    for lo, hi in segments:
        s += f"  \\fill[{FILL_QUERY}] ({lo},0) rectangle ({hi + 1},0.8);\n"
    for i, r in enumerate(curve_cover):
        lo, hi = r.start[0], r.end[0]
        s += f"  \\draw[fill={FILL_COVER[i % len(FILL_COVER)]},draw=black,thick] ({lo},0) rectangle ({hi + 1},0.8);\n"
    s += f"  \\node[anchor=east] at (0,0.4) {{0}};\n"
    s += f"  \\node[anchor=west] at ({n_cells},0.4) {{{n_cells - 1}}};\n"
    s += f"  \\node[anchor=north] at ({n_cells / 2},-0.2) {{(c) $H$: the segments of (b), {len(curve_cover)} binary-tree ranges}};\n"
    s += "\\end{scope}\n"
    s += "\\end{tikzpicture}\n"
    s += (f"% query {query}; native BRC {len(native_cover)} ranges; segments {segments}; "
          f"curve BRC {len(curve_cover)} ranges; boundary cells {len(boundary)}\n")
    return s


# --------------------------------------------------------------------------- #
# Figure 2: curve-tree ranges are boxes; a product range need not be an interval
# --------------------------------------------------------------------------- #
def fig_curve_ranges(order: int = 2) -> str:
    side = 2**order
    hc = HilbertCurve(order, 2)
    n_cells = side * side

    def panel(xshift: float, cells_fill: List[Point], title: str, extra: str = "") -> str:
        p = f"\\begin{{scope}}[xshift={xshift}cm]\n"
        p += _cells(cells_fill, FILL_QUERY)
        p += f"  \\draw[gray!60,very thin,xstep=1,ystep=1] (0,0) grid ({side},{side});\n"
        p += _curve_path(hc, n_cells, "gray!75,thin")
        for d in range(n_cells):
            pt = hc.point_from_distance(d)
            p += f"  \\node[font=\\tiny] at ({pt[0] + 0.5},{pt[1] + 0.5}) {{{d}}};\n"
        p += extra
        p += f"  \\node[anchor=north,align=center] at ({side / 2},-0.25) {{{title}}};\n"
        p += "\\end{scope}\n"
        return p

    # (a) a curve-tree vertex [0,3]: one aligned sub-square
    cells_a = [hc.point_from_distance(d) for d in range(0, 4)]
    # (b) a curve-tree vertex [0,7]: two adjacent sub-squares, a 2x4 box
    cells_b = [hc.point_from_distance(d) for d in range(0, 8)]
    # (c) the product vertex [0,3]x[0,1]
    prod = HyperRange.from_coords([0, 0], [side - 1, 1])
    cells_c = prod.points()
    dists_c = sorted(hc.distance_from_point(p) for p in cells_c)
    runs: List[Tuple[int, int]] = []
    for d in dists_c:
        if runs and runs[-1][1] + 1 == d:
            runs[-1] = (runs[-1][0], d)
        else:
            runs.append((d, d))
    extra_c = "".join(_curve_run(hc, lo, hi, "black,line width=1.4pt") for lo, hi in runs)

    s = "% generated by scripts/gen_concept_figures.py -- do not edit\n"
    s += "\\begin{tikzpicture}[x=0.42cm,y=0.42cm,font=\\scriptsize]\n"
    s += panel(0.0, cells_a, "(a) curve vertex $[0,3]$\\\\ $=[0,1]\\times[0,1]$")
    s += panel(2.75, cells_b, "(b) curve vertex $[0,7]$\\\\ $=[0,1]\\times[0,3]$")
    runs_txt = ", ".join(f"[{lo},{hi}]" if lo != hi else f"{lo}" for lo, hi in runs)
    s += panel(5.6, cells_c, f"(c) product $[0,{side - 1}]\\times[0,1]$\\\\ $=$ runs {runs_txt}", extra_c)
    s += "\\end{tikzpicture}\n"
    s += f"% distances of (c): {dists_c}\n"
    return s


# --------------------------------------------------------------------------- #
# Figure 3: packed R-tree leaves, Hilbert order versus STR
# --------------------------------------------------------------------------- #
def _clustered_points(seed: int = 7, side: int = 16, n: int = 24) -> List[Point]:
    rng = random.Random(seed)
    centres = [(3, 3), (11, 12), (12, 4)]
    pts = set()
    while len(pts) < n:
        cx, cy = centres[rng.randrange(len(centres))]
        x = min(side - 1, max(0, int(rng.gauss(cx, 1.8))))
        y = min(side - 1, max(0, int(rng.gauss(cy, 1.8))))
        pts.add((x, y))
    return [Point([x, y]) for x, y in sorted(pts)]


def _draw_rtree(root, depth: int = 0) -> str:
    out = ""
    for child in root.children:
        if child.is_leaf:
            out += _rect(child.bbox, f"fill={FILL_COVER[child.node_id % len(FILL_COVER)]},fill opacity=0.7,draw=black,thick")
        else:
            out += _rect(child.bbox, "draw=black,dashed,thin")
            out += _draw_rtree(child, depth + 1)
    return out


def fig_rtree_packing(side: int = 16, capacity: int = 4) -> str:
    pts = _clustered_points(side=side)
    order = side.bit_length() - 1
    htree = HilbertRTree.build(pts, 2, order, capacity)
    stree = STRRTree.build(pts, 2, capacity)
    hc = HilbertCurve(order, 2)

    def leaves(root) -> List:
        return [n for n in root.children] if all(c.is_leaf for c in root.children) else [
            leaf for c in root.children for leaf in leaves(c)
        ]

    def area(r: HyperRange) -> int:
        return (r.end[0] - r.start[0] + 1) * (r.end[1] - r.start[1] + 1)

    def panel(xshift: float, tree, title: str, curve: bool) -> str:
        p = f"\\begin{{scope}}[xshift={xshift}cm]\n"
        p += f"  \\draw[gray!50,very thin,xstep=1,ystep=1] (0,0) grid ({side},{side});\n"
        if curve:
            p += _curve_path(hc, side * side, "gray!55,thin")
        p += _draw_rtree(tree.root)
        for q in pts:
            p += f"  \\fill[black] ({q[0] + 0.5},{q[1] + 0.5}) circle (0.18);\n"
        p += f"  \\node[anchor=north] at ({side / 2},-0.3) {{{title}}};\n"
        p += "\\end{scope}\n"
        return p

    hl, sl = leaves(htree.root), leaves(stree.root)
    s = "% generated by scripts/gen_concept_figures.py -- do not edit\n"
    s += "\\begin{tikzpicture}[x=0.17cm,y=0.17cm,font=\\scriptsize]\n"
    s += panel(0.0, htree, f"(a) Hilbert order, leaf area {sum(area(l.bbox) for l in hl)}", True)
    s += panel(side * 0.17 + 0.5, stree, f"(b) STR, leaf area {sum(area(l.bbox) for l in sl)}", False)
    s += "\\end{tikzpicture}\n"
    s += f"% {len(pts)} points, capacity {capacity}; hilbert leaves {len(hl)}, str leaves {len(sl)}\n"
    return s


# --------------------------------------------------------------------------- #
# Figure 4: uniform versus mass-based TDAG cuts on one-dimensional data
# --------------------------------------------------------------------------- #
def fig_divider(bits: int = 4) -> str:
    n = 2**bits
    # clustered one-dimensional data: counts per coordinate
    counts = {1: 1, 2: 3, 3: 4, 4: 2, 5: 1, 9: 1, 13: 2, 14: 3}
    mm: Dict[Point, List[bytes]] = {Point([x]): [b"r"] * c for x, c in counts.items()}
    dom = HyperRange.from_coords([0], [n - 1])
    uni = UniformSplitMidOverlapDivider(2)
    mass = DataDependentSplitMidOverlapDivider(2, mm, weight="records")

    def two_levels(div) -> List[List[HyperRange]]:
        lvl1 = div.divide(dom)
        chunks = [r for r in lvl1 if r.start[0] == 0 or r.end[0] == n - 1]  # the two chunks, not the cousin
        lvl2 = [c for ch in chunks for c in div.divide(ch)]
        return [lvl1, lvl2]

    def panel(yshift: float, levels: List[List[HyperRange]], title: str) -> str:
        p = f"\\begin{{scope}}[yshift={yshift}cm]\n"
        p += f"  \\draw[gray!60,thin] (0,0) rectangle ({n},0.6);\n"
        for x in range(1, n):
            p += f"  \\draw[gray!40,very thin] ({x},0) -- ({x},0.6);\n"
        for x, c in counts.items():
            for k in range(c):
                p += f"  \\fill[black] ({x + 0.5},{0.1 + 0.13 * k}) circle (0.09);\n"
        p += f"  \\node[anchor=east] at (-0.15,0.3) {{0}};\n  \\node[anchor=west] at ({n + 0.15},0.3) {{{n - 1}}};\n"
        y = 0.95
        for lvl in levels:
            chunks = [r for r in lvl if not _is_cousin(r, lvl)]
            cousins = [r for r in lvl if _is_cousin(r, lvl)]
            for r in chunks:
                p += f"  \\draw[black,thick] ({r.start[0]},{y}) -- ({r.end[0] + 1},{y});\n"
                p += f"  \\draw[black,thick] ({r.start[0]},{y - 0.1}) -- ({r.start[0]},{y + 0.1}) ({r.end[0] + 1},{y - 0.1}) -- ({r.end[0] + 1},{y + 0.1});\n"
            for r in cousins:
                p += f"  \\draw[black,dashed,thick] ({r.start[0]},{y + 0.35}) -- ({r.end[0] + 1},{y + 0.35});\n"
                p += f"  \\draw[black,thick] ({r.start[0]},{y + 0.25}) -- ({r.start[0]},{y + 0.45}) ({r.end[0] + 1},{y + 0.25}) -- ({r.end[0] + 1},{y + 0.45});\n"
            y += 0.85
        p += f"  \\node[anchor=west,align=left] at ({n + 0.6},{y - 0.6}) {{{title}}};\n"
        p += "\\end{scope}\n"
        return p

    def _is_cousin(r: HyperRange, lvl: List[HyperRange]) -> bool:
        # a cousin straddles the seam between two chunks: it overlaps two other ranges of the level
        return sum(1 for o in lvl if o is not r and o.intersects(r)) >= 2

    s = "% generated by scripts/gen_concept_figures.py -- do not edit\n"
    s += "\\begin{tikzpicture}[x=0.38cm,y=0.38cm,font=\\scriptsize]\n"
    s += panel(0.0, two_levels(mass), "(b) record-balanced")
    s += panel(1.9, two_levels(uni), "(a) uniform")
    s += "\\end{tikzpicture}\n"
    s += f"% counts {counts}; uniform {[str(r) for r in two_levels(uni)[0]]}; mass {[str(r) for r in two_levels(mass)[0]]}\n"
    return s


# --------------------------------------------------------------------------- #
# Figure 5: the two rounds of the interactive double index (schematic)
# --------------------------------------------------------------------------- #
def fig_interactive() -> str:
    return r"""% generated by scripts/gen_concept_figures.py -- do not edit
\begin{tikzpicture}[font=\scriptsize,
  actor/.style={draw,rounded corners=2pt,inner sep=3pt,align=center,fill=black!6},
  idx/.style={draw,inner sep=2.5pt,align=left,fill=black!4},
  lab/.style={above,align=center,inner sep=1.5pt},
  tok/.style={->,thick}, ans/.style={->,thick,dashed}]
  \node[actor] (c) at (0,0) {client};
  \node[actor] (s) at (5.4,0) {server};
  \draw[gray!60] (c.south) -- ++(0,-3.45);
  \draw[gray!60] (s.south) -- ++(0,-4.0);
  \draw[tok] (0,-0.7) -- node[lab] {round 1: one token,\\ the vertex of index 1 that covers $q$} (5.4,-0.7);
  \draw[ans] (5.4,-1.35) -- node[lab] {the triples $(x,lo,hi)$ stored under that vertex} (0,-1.35);
  \node[align=center,fill=white,inner sep=1.5pt] at (2.7,-1.9) {the client keeps the triples with $x\in q$\\ and merges their $[lo,hi]$ into runs};
  \draw[tok] (0,-2.75) -- node[lab] {round 2: the \src{} or \brc{} of each run in index 2} (5.4,-2.75);
  \draw[ans] (5.4,-3.45) -- node[lab] {the records of the runs, without false positives} (0,-4.0);
  \node[idx,anchor=west] at (5.55,-1.0) {index 1: TDAG over\\ the \emph{value} domain};
  \node[idx,anchor=west] at (5.55,-3.1) {index 2: TDAG over the\\ \emph{document-index} domain};
\end{tikzpicture}
"""


FIGURES = {
    "fig_domains.tex": fig_domains,
    "fig_curve_ranges.tex": fig_curve_ranges,
    "fig_rtree_packing.tex": fig_rtree_packing,
    "fig_divider.tex": fig_divider,
    "fig_interactive.tex": fig_interactive,
}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="figures/concept", help="output directory for the .tex files")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, fn in FIGURES.items():
        (out / name).write_text(fn())
        print(f"wrote {out / name}")


if __name__ == "__main__":
    main()
